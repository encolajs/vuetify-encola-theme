// Fallback set: aliases and page icons are components, so Vuetify renders
// them through VComponentIcon before this set is consulted. It only sees
// raw string names, which this theme does not use.
export const lucide: IconSet = {
  component: (props: IconProps) =>
    h(props.tag as string, props.icon ? [h(props.icon as never)] : undefined),
}
